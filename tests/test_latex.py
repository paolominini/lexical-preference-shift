"""Fast tests for the thesis formatting helpers (latex.py)."""
from __future__ import annotations

import pytest

from probing.config import load_config
from probing.latex import (MODEL_LABELS, display_labels, escape_tex, fmt_ci, fmt_num, fmt_p, fmt_p_bound, fmt_range, ordered_categories,
                           table_env, tabular, write_fragment)
from probing.pools import load_prefixes


def test_escape_special_characters() -> None:
    assert escape_tex("a_b & 50% $x$ #1 {y}") == r"a\_b \& 50\% \$x\$ \#1 \{y\}"
    assert escape_tex("Sex Worker") == "Sex Worker"


def test_fmt_num_signs_and_no_negative_zero() -> None:
    assert fmt_num(0.5079, signed=True) == "$+0.51$"
    assert fmt_num(-0.5412, signed=True) == "$-0.54$"
    assert fmt_num(-0.0007, signed=True) == "$0.00$"
    assert fmt_num(-0.0007) == "$0.00$"
    assert fmt_num(0.123456, nd=3, math_mode=False) == "0.123"


def test_fmt_ci_and_range() -> None:
    assert fmt_ci(0.44797, 0.56791) == "$[0.45, 0.57]$"
    assert fmt_ci(-0.04499, 0.07823) == "$[-0.04, 0.08]$"
    assert fmt_range(0.4893, 0.6365) == "$0.49$--$0.64$"


@pytest.mark.parametrize("p, expected", [
    (0.2587, "$0.26$"), (0.0015, "$0.0015$"), (0.028, "$0.028$"), (1.0, "$1.00$"), (0.9996, "$1.00$"),
    (1.6753e-44, "$1.7 \\times 10^{-44}$"), (9.96e-5, "$1.0 \\times 10^{-4}$"), (4.9233e-05, "$4.9 \\times 10^{-5}$"),
    (float("nan"), "--"),
])
def test_fmt_p(p: float, expected: str) -> None:
    assert fmt_p(p) == expected


def test_fmt_p_bound() -> None:
    assert fmt_p_bound(6.9587e-08) == "$\\le 7.0 \\times 10^{-8}$"


def test_tabular_structure_and_width_check() -> None:
    t = tabular("lr", ["a", "b"], [["1", "2"], ["3", "4"]], midrules=(1,))
    lines = t.splitlines()
    assert lines[1] == "\\toprule" and lines[-2] == "\\bottomrule"
    assert t.count("\\midrule") == 2 and t.count("\\\\") == 3
    with pytest.raises(ValueError):
        tabular("lr", ["a", "b"], [["1"]])


def test_table_env_has_caption_label_note() -> None:
    t = table_env("BODY", "Cap.", "tab:x", note="Note.")
    assert "\\caption[{Cap}]{Cap. Note.}" in t and "\\label{tab:x}" in t and "minipage" not in t
    assert t.startswith("\\begin{table}") and t.endswith("\\end{table}")
    assert "\\caption[{Cap}]{Cap.}" in table_env("BODY", "Cap", "tab:x")
    assert "\\caption[{Why?}]{Why? Note.}" in table_env("BODY", "Why?", "tab:x", note="Note.")
    assert "\\caption[{Short}]{Long caption.}" in table_env("BODY", "Long caption", "tab:x", short="Short")


def test_display_labels_cover_every_category() -> None:
    labels = display_labels(load_config())
    cats = set(load_prefixes()["category"])
    assert cats == set(labels)
    assert labels["African - Afro American"] == "Black Person" and labels["Female Homosexual"] == "Homosexual Woman"
    assert len(set(labels.values())) == 5


def test_ordered_categories_follow_display_labels() -> None:
    cfg = load_config()
    labels = [display_labels(cfg)[c] for c in ordered_categories(cfg)]
    assert labels == ["Black Person", "Homosexual Man", "Homosexual Woman", "Sex Worker", "Transgender Woman"]


def test_model_labels() -> None:
    assert list(MODEL_LABELS) == ["base"] + list(load_config()["models"]["1.4b"])[1:]


def test_write_fragment_header_names_generator(tmp_path) -> None:
    write_fragment(tmp_path / "a.tex", "x", ["s.csv"])
    write_fragment(tmp_path / "b.tex", "x", ["s.csv"], generator="scripts/11d_scale_assets.py")
    assert (tmp_path / "a.tex").read_text().startswith("% Generated by scripts/11_thesis_tables.py - do not edit")
    assert (tmp_path / "b.tex").read_text() == ("% Generated by scripts/11d_scale_assets.py - do not edit by hand; rerun the script "
                                               "instead.\n% Sources: s.csv\nx\n")
